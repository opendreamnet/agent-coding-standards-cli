import {
  CST,
  isAlias,
  isMap,
  isScalar,
  isSeq,
  parseDocument,
  stringify,
  type Scalar,
} from 'yaml'

/**
 * Selects ordered profiles from a stable rules version pinned to its commit.
 * These fields are reserved at the YAML root; other metadata remains opaque.
 */
export interface StandardsConfig {
  repository: string
  version: string
  revision: string
  profiles: string[]
}

/**
 * Separates validated configuration from the untouched document text.
 */
export interface CodingDocument {
  config: StandardsConfig
  /**
   * Original front matter, including delimiters, BOM and closing line ending.
   */
  header: string
  body: string
}

interface ParsedHeader {
  document: CodingDocument
  yamlOffset: number
  version: Scalar<string>
  revision: Scalar<string>
}

const generatedMarker =
  '# Generated by acs. Project-specific exceptions belong in AGENTS.md.'

/**
 * Returns an owner/repo slug from that format or an exact HTTPS GitHub URL;
 * surrounding whitespace and unsupported repository identifiers are rejected.
 */
export function normalizeRepository(value: string): string {
  if (typeof value !== 'string' || value.trim() !== value) {
    throw new Error('Invalid coding standards repository')
  }

  const repository = value.startsWith('https://github.com/')
    ? value.slice('https://github.com/'.length)
    : value

  const match =
    /^[a-zA-Z0-9](?:[a-zA-Z0-9-]{0,37}[a-zA-Z0-9])?\/(?<repository>[a-zA-Z0-9_.-]{1,100})$/.exec(
      repository,
    )

  if (
    match == null ||
    match.groups?.repository === '.' ||
    match.groups?.repository === '..'
  ) {
    throw new Error('Invalid coding standards repository')
  }

  return repository
}

/**
 * Requires an unprefixed stable semantic version with safe integer components.
 */
export function validateVersion(value: string): string {
  if (
    typeof value !== 'string' ||
    value.trim() !== value ||
    !/^(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)$/.test(value) ||
    !value
      .split('.')
      .every((component) => Number.isSafeInteger(Number(component)))
  ) {
    throw new Error('Invalid coding standards version')
  }

  return value
}

/**
 * Validates both stable versions and compares their numeric components,
 * returning a negative, zero or positive value for their relative order.
 */
export function compareVersions(left: string, right: string): number {
  const leftParts = validateVersion(left).split('.').map(Number)
  const rightParts = validateVersion(right).split('.').map(Number)

  return (
    leftParts[0] - rightParts[0] ||
    leftParts[1] - rightParts[1] ||
    leftParts[2] - rightParts[2]
  )
}

/**
 * Returns a copy of ordered, unique profile identifiers; empty selections,
 * duplicates and names unsuitable for profile paths are rejected.
 */
export function validateProfiles(value: unknown): string[] {
  if (!Array.isArray(value) || value.length === 0) {
    throw new Error('Coding standards profiles must be a nonempty array')
  }

  const profiles: string[] = []

  for (const profile of value) {
    if (
      typeof profile !== 'string' ||
      profile.trim() !== profile ||
      !/^[a-z][a-z0-9-]*$/.test(profile) ||
      profiles.includes(profile)
    ) {
      throw new Error('Invalid or duplicate coding standards profile')
    }

    profiles.push(profile)
  }

  return profiles
}

/**
 * Requires a complete lowercase hexadecimal commit SHA for immutable downloads.
 */
function validateRevision(value: unknown): string {
  if (
    typeof value !== 'string' ||
    value.length !== 40 ||
    !/^[0-9a-f]+$/.test(value)
  ) {
    throw new Error('Invalid coding standards revision')
  }

  return value
}

/**
 * Narrows untrusted configuration and validates every CLI-owned field,
 * normalizing only the repository identifier and preserving profile order.
 */
function validateConfig(value: unknown): StandardsConfig {
  if (
    value == null ||
    typeof value !== 'object' ||
    !('repository' in value) ||
    typeof value.repository !== 'string' ||
    !('version' in value) ||
    typeof value.version !== 'string' ||
    !('revision' in value) ||
    !('profiles' in value)
  ) {
    throw new Error('Missing or invalid coding standards configuration')
  }

  return {
    repository: normalizeRepository(value.repository),
    version: validateVersion(value.version),
    revision: validateRevision(value.revision),
    profiles: validateProfiles(value.profiles),
  }
}

/**
 * Rejects aliases, anchors, explicit tags, merge keys and excessive nesting in
 * CLI-owned YAML so configuration and scalar edits have unambiguous locations.
 */
function validateOwnedYaml(node: unknown, depth = 0): void {
  if (
    depth > 100 ||
    isAlias(node) ||
    ((isMap(node) || isSeq(node) || isScalar(node)) &&
      (node.tag != null || node.anchor != null))
  ) {
    throw new Error(
      'Aliases, anchors and tags are not allowed in CLI-owned YAML fields',
    )
  }

  if (isMap(node)) {
    for (const item of node.items) {
      if (isScalar(item.key) && item.key.value === '<<') {
        throw new Error('Merge keys are not allowed in CLI-owned YAML fields')
      }

      validateOwnedYaml(item.key, depth + 1)
      validateOwnedYaml(item.value, depth + 1)
    }
  } else if (isSeq(node)) {
    for (const item of node.items) {
      validateOwnedYaml(item, depth + 1)
    }
  }
}

/**
 * Requires a string-valued YAML scalar with source offsets for lossless edits.
 */
function getStringScalar(node: unknown): Scalar<string> {
  if (
    !isScalar<string>(node) ||
    typeof node.value !== 'string' ||
    node.range == null
  ) {
    throw new Error('Coding standards fields must be string scalars')
  }

  return node
}

/**
 * Validates delimited YAML and returns the original text plus owned scalar
 * locations without resolving unrelated metadata. Errors report offsets rather
 * than source excerpts to avoid exposing values from the front matter.
 */
function parseHeader(content: string): ParsedHeader {
  const opening = /^\uFEFF?---[ \t]*\r?\n/.exec(content)

  if (opening == null) {
    throw new Error('CODING.md requires YAML front matter')
  }

  const yamlOffset = opening[0].length
  const closing = /^---[ \t]*(?:\r?\n|$)/m.exec(content.slice(yamlOffset))

  if (closing == null) {
    throw new Error('CODING.md front matter is not closed')
  }

  const headerEnd = yamlOffset + closing.index + closing[0].length

  const yaml = parseDocument(
    content.slice(yamlOffset, yamlOffset + closing.index),
    {
      keepSourceTokens: true,
      prettyErrors: false,
      strict: true,
      uniqueKeys: true,
    },
  )

  if (yaml.errors.length > 0) {
    const [error] = yaml.errors

    throw new Error(
      `Invalid CODING.md YAML at offset ${yamlOffset + error.pos[0]}`,
    )
  }

  if (!isMap(yaml.contents)) {
    throw new Error('CODING.md front matter must be a mapping')
  }

  /*
   * The native compiler requires strict absence checks for root-map metadata.
   */
  if (
    (yaml.contents.tag !== undefined && yaml.contents.tag !== null) ||
    (yaml.contents.anchor !== undefined && yaml.contents.anchor !== null) ||
    yaml.contents.items.some(
      (item) => isScalar(item.key) && item.key.value === '<<',
    )
  ) {
    throw new Error(
      'CODING.md requires an untagged root mapping without anchors or merge keys',
    )
  }

  for (const name of ['repository', 'version', 'revision', 'profiles']) {
    const pair = yaml.contents.items.find(
      (item) => isScalar(item.key) && item.key.value === name,
    )

    if (pair === undefined) {
      throw new Error(
        'CODING.md requires explicit repository, version, revision and profiles fields at the YAML root',
      )
    }

    validateOwnedYaml(pair.key)
    validateOwnedYaml(pair.value)
  }

  const repository = getStringScalar(
    yaml.contents.get('repository', true),
  ).value

  const version = getStringScalar(yaml.contents.get('version', true))
  const revision = getStringScalar(yaml.contents.get('revision', true))
  const profiles = yaml.contents.get('profiles', true)

  if (!isSeq(profiles)) {
    throw new Error('Coding standards profiles must be a nonempty array')
  }

  const profileNames: string[] = []

  for (const item of profiles.items) {
    profileNames.push(getStringScalar(item).value)
  }

  const config = validateConfig({
    repository,
    version: version.value,
    revision: revision.value,
    profiles: profileNames,
  })

  if (repository !== config.repository) {
    throw new Error('CODING.md repository must use owner/repo format')
  }

  return {
    document: {
      config,
      header: content.slice(0, headerEnd),
      body: content.slice(headerEnd),
    },
    yamlOffset,
    version,
    revision,
  }
}

/**
 * Parses configuration without reserializing or resolving unrelated YAML data.
 */
export function parseCodingDocument(content: string): CodingDocument {
  return parseHeader(content).document
}

/**
 * Composes selected Markdown in order with deterministic LF separators,
 * preserving significant indentation and rejecting empty or reserved content.
 */
export function renderCodingBody(profileContents: string[]): string {
  if (!Array.isArray(profileContents) || profileContents.length === 0) {
    throw new Error('Profile contents must be a nonempty array')
  }

  const contents = Array.from(profileContents, (content) => {
    if (typeof content !== 'string') {
      throw new Error('Profile content must be Markdown text')
    }

    /*
     * Trim blank boundaries without removing code indentation or Markdown hard breaks.
     */
    const normalized = content
      .replace(/\r\n/g, '\n')
      .replace(/^(?:[ \t]*\n)+/, '')
      .replace(/\n(?:[ \t]*\n)*[ \t]*$/, '')

    if (
      normalized.trim().length === 0 ||
      normalized.includes('Generated by acs.') ||
      /^---[ \t]*(?:\n|$)/.test(normalized)
    ) {
      throw new Error(
        'Profile content is empty or contains reserved document markers',
      )
    }

    return normalized
  })

  return `\n${contents.join('\n\n')}\n`
}

/**
 * Creates canonical front matter after validating configuration and requiring
 * one Markdown document per selected profile.
 */
export function createCodingDocument(
  config: StandardsConfig,
  profileContents: string[],
): string {
  const validated = validateConfig(config)

  const body = renderCodingBody(profileContents)

  if (validated.profiles.length !== profileContents.length) {
    throw new Error('Profile contents must match the selected profiles')
  }

  return `---\n${generatedMarker}\n${stringify(validated)}---\n${body}`
}

/**
 * Changes only version and revision source tokens in the original header,
 * preserving unrelated bytes, comments and supported scalar styles.
 */
export function updateCodingVersion(
  document: CodingDocument,
  version: string,
  revision: string,
): string {
  const values = [validateVersion(version), validateRevision(revision)]

  const parsed = parseHeader(document.header)
  const scalars = [parsed.version, parsed.revision]

  const edits: { start: number; end: number; replacement: string }[] = []

  for (let index = 0; index < scalars.length; index += 1) {
    const scalar = scalars[index]

    if (scalar.value === values[index]) {
      continue
    }

    const token = scalar.srcToken
    const { range } = scalar

    if (
      range === null ||
      range === undefined ||
      token === null ||
      token === undefined ||
      (token.type !== 'scalar' &&
        token.type !== 'single-quoted-scalar' &&
        token.type !== 'double-quoted-scalar' &&
        token.type !== 'block-scalar')
    ) {
      throw new Error('Missing coding standards scalar source token')
    }

    const originalToken = CST.stringify(token)
    const start = parsed.yamlOffset + range[0]
    const end = start + originalToken.length

    if (document.header.slice(start, end) !== originalToken) {
      throw new Error('Invalid coding standards scalar source span')
    }

    /*
     * CST scalar edits do not consult a schema. Let YAML's stringifier choose
     * a safe style, including quotes for numeric and exponent-like commit SHAs.
     */
    const replacement = getStringScalar(
      parseDocument(
        stringify(values[index], {
          defaultStringType: scalar.type,
          singleQuote: true,
          lineWidth: 0,
        }),
      ).contents,
    )

    const originalSource = token.source

    const blockHeader =
      token.type === 'block-scalar' &&
      token.props[0].type === 'block-scalar-header'
        ? { token: token.props[0], source: token.props[0].source }
        : undefined

    CST.setScalarValue(token, values[index], { type: replacement.type })

    if (token.type === 'block-scalar' && blockHeader !== undefined) {
      /*
       * Validated owned values are single-line, whitespace-free strings. Keep
       * their original whitespace envelope and block header because CST edits
       * otherwise normalize indentation, chomping indicators and CRLF to LF.
       * The replacement value itself is serialized by CST, not by this layer.
       */
      token.source = originalSource.replace(scalar.value, token.source.trim())
      blockHeader.token.source = blockHeader.source
    }

    edits.push({ start, end, replacement: CST.stringify(token) })
  }

  let { header } = document

  for (const edit of edits.toSorted(
    (left, right) => right.start - left.start,
  )) {
    header =
      header.slice(0, edit.start) + edit.replacement + header.slice(edit.end)
  }

  return header
}
