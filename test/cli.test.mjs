test('sync is byte-idempotent and retains comments and unknown front matter keys', async (t) => {
  const fixture = await createFixture(t)
  const document = await initialize(fixture)
  const original = customHeader(fixture) + document.body

  await writeFile(fixture.codingPath, original)
  await setTags(fixture, ['v1.0.0', 'v1.10.0'])
  await writeFile(fixture.tracePath, '')

  for (let attempt = 0; attempt < 2; attempt += 1) {
    const result = await runCli(['sync', '-C', fixture.directory], fixture)

    assert.equal(result.status, 0, result.stderr)
    assert.equal(await readFile(fixture.codingPath, 'utf8'), original)
    assert.doesNotMatch(result.stdout + result.stderr, new RegExp(secret))
  }

  assert.doesNotMatch(await getTrace(fixture), /ref-prefix refs\/tags\/$/m)

  const synced = await getCoding(fixture)

  assert.equal(synced.config.revision, fixture.versions['1.0.0'].sha)
})

