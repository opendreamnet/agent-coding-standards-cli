/**
 * Execute the selected Node entry point or native binary against the local remote
 * without inherited GitHub credentials; capture output and numeric exit status.
 * Propagate execution failures that do not provide a numeric exit code.
 */
async function runCli(args, fixture) {
  const env = getEnvironment(fixture)

  await configureRemote(fixture)

  try {
    const result = await execute(
      binary ?? process.execPath,
      binary ? args : [entry, ...args],
      { encoding: 'utf8', env, timeout: 30_000 },
    )

    return { status: 0, stdout: result.stdout, stderr: result.stderr }
  } catch (error) {
    if (typeof error.code !== 'number') {
      throw error
    }

    return { status: error.code, stdout: error.stdout, stderr: error.stderr }
  }
}

/**
 * Run the selected CLI against the local remote in a Linux pseudo-terminal without
 * inherited GitHub credentials. Send the supplied answer at the first confirmation
 * prompt and return the combined output, exit status and whether a prompt was seen.
 */
async function runInteractiveCli(args, fixture, answer, beforeAnswer) {
  const env = getEnvironment(fixture)

  await configureRemote(fixture)

  const invocation = binary
    ? [binary, ...args]
    : [process.execPath, entry, ...args]

  const command = invocation
    .map((argument) => `'${argument.replaceAll("'", String.raw`'\''`)}'`)
    .join(' ')

  const child = spawn('script', ['-q', '-e', '-c', command, '/dev/null'], {
    env,
    timeout: 30_000,
  })

  let output = ''
  let answered = false

  let answerTask = Promise.resolve()
  let answerError

  /**
   * Finish any concurrent edit before answering, and stop the terminal on failure.
   */
  async function sendAnswer() {
    try {
      await beforeAnswer?.()

      child.stdin.write(`${answer}\n`)
    } catch (error) {
      answerError = error
      child.kill()
    }
  }

  child.stdout.on('data', (chunk) => {
    output += chunk.toString()

    if (!answered && output.includes('[y/N]')) {
      answered = true

      answerTask = sendAnswer()
    }
  })

  child.stderr.on('data', (chunk) => {
    output += chunk.toString()
  })

  const [status] = await once(child, 'close')

  await answerTask

  if (answerError !== undefined) {
    throw answerError
  }

  return { status, output, answered }
}

/**
 * Isolate credentials and Git configuration while retaining native Git execution.
 */
function getEnvironment(fixture) {
  const env = { ...process.env }

  for (const key of Object.keys(env)) {
    if (key.startsWith('GIT_')) {
      delete env[key]
    }
  }

  delete env.GH_TOKEN
  delete env.GITHUB_TOKEN
  delete env.CODING_STANDARDS_API_URL

  return {
    ...env,
    GIT_CONFIG_GLOBAL: fixture.configPath,
    GIT_CONFIG_NOSYSTEM: '1',
    GIT_TERMINAL_PROMPT: '0',
    GIT_EXEC_PATH: fixture.binPath,
    PATH: `${fixture.binPath}:${env.PATH}`,
    ...fixture.environment,
  }
}

/**
 * Redirect both public transports to an isolated bare remote through Git config.
 */
async function configureRemote(fixture) {
  const url = pathToFileURL(fixture.remotePath).href

  const unavailable = pathToFileURL(
    join(fixture.directory, 'missing-remote.git'),
  ).href

  const httpsUrl = fixture.expectedTransport === 'ssh' ? unavailable : url
  const sshUrl = fixture.expectedTransport === 'https' ? unavailable : url

  await writeFile(
    fixture.configPath,
    `[url "${httpsUrl}"]\n  insteadOf = https://github.com/${fixture.repository}.git\n[url "${sshUrl}"]\n  insteadOf = git@github.com:${fixture.repository}.git\n`,
  )
}

/**
 * Run actual Git with isolated configuration and command-local fixture identity.
 */
async function runGit(fixture, args, directory = fixture.workPath) {
  const env = getEnvironment(fixture)

  env.GIT_AUTHOR_DATE = '2026-01-01T00:00:00Z'
  env.GIT_COMMITTER_DATE = '2026-01-01T00:00:00Z'

  return execute(
    'git',
    [
      '-c',
      'user.name=Standards Fixture',
      '-c',
      'user.email=fixture@example.invalid',
      '-c',
      'commit.gpgsign=false',
      '-c',
      'tag.gpgsign=false',
      ...args,
    ],
    { cwd: directory, env, encoding: 'utf8', timeout: 30_000 },
  )
}

/**
 * Commit immutable profile files and publish a lightweight release in the fixture.
 */
async function publishRelease(fixture, version, files) {
  await rm(join(fixture.workPath, 'profiles'), { recursive: true, force: true })
  await mkdir(join(fixture.workPath, 'profiles'))

  for (const [profile, content] of Object.entries(files)) {
    await writeFile(
      join(fixture.workPath, 'profiles', `${profile}.md`),
      content,
    )
  }

  await runGit(fixture, ['add', '--all'])
  await runGit(fixture, ['commit', '--allow-empty', '-m', `Release ${version}`])

  const { stdout } = await runGit(fixture, ['rev-parse', 'HEAD'])

  fixture.versions[version] = { sha: stdout.trim(), files }

  await runGit(fixture, ['tag', '-f', `v${version}`])

  await runGit(fixture, [
    'push',
    '--force',
    fixture.remotePath,
    `refs/tags/v${version}`,
  ])
}

/**
 * Replace advertised fixture tags without changing the underlying commit objects.
 */
async function setTags(fixture, tags) {
  const { stdout } = await runGit(
    fixture,
    ['tag', '--list'],
    fixture.remotePath,
  )

  for (const tag of stdout.trim().split('\n').filter(Boolean)) {
    await runGit(
      fixture,
      ['update-ref', '-d', `refs/tags/${tag}`],
      fixture.remotePath,
    )
  }

  for (const tag of tags) {
    const sha =
      fixture.versions[tag.slice(1)]?.sha ?? fixture.versions['1.0.0'].sha

    await runGit(
      fixture,
      ['update-ref', `refs/tags/${tag}`, sha],
      fixture.remotePath,
    )
  }
}

/**
 * Read real upload-pack packet traces to detect remote access and tag discovery.
 */
async function getTrace(fixture) {
  return readFile(fixture.tracePath, 'utf8')
}

/**
 * Snapshot all consumer Git files by relative path and bytes without invoking Git.
 */
async function snapshotGit(directory, prefix = '') {
  const entries = await readdir(directory, { withFileTypes: true })
  const snapshot = {}

  for (const item of entries) {
    const path = join(directory, item.name)
    const name = join(prefix, item.name)

    if (item.isDirectory()) {
      Object.assign(snapshot, await snapshotGit(path, name))
    } else {
      snapshot[name] = await readFile(path)
    }
  }

  return snapshot
}

/**
 * Create real release commits, a bare remote and an independent consumer repository.
 * Cleanup verifies consumer Git bytes and unrelated files before removing fixtures.
 */
async function createFixture(t) {
  const root = await mkdtemp(join(tmpdir(), 'standards-cli-'))
  const directory = join(root, 'consumer')

  const fixture = {
    directory,
    codingPath: join(directory, 'CODING.md'),
    repository,
    workPath: join(root, 'rules'),
    remotePath: join(root, 'remote.git'),
    configPath: join(root, 'gitconfig'),
    tracePath: join(root, 'git-trace'),
    binPath: join(root, 'bin'),
    removeTagPath: join(root, 'remove-pinned-tag'),
    versions: {},
  }

  t.after(async () => {
    try {
      if (fixture.gitSnapshot) {
        assert.deepEqual(
          await snapshotGit(join(directory, '.git')),
          fixture.gitSnapshot,
        )
      }

      for (const [name, content] of Object.entries(unrelatedFiles)) {
        assert.equal(await readFile(join(directory, name), 'utf8'), content)
      }
    } finally {
      await rm(root, { recursive: true, force: true })
    }
  })

  await mkdir(directory)
  await mkdir(fixture.workPath)
  await mkdir(fixture.binPath)
  await writeFile(fixture.tracePath, '')

  const wrapper = join(fixture.binPath, 'git-upload-pack')

  /*
   * Delegate every transfer to real Git. Server packet logs distinguish exact
   * tag fetches from latest discovery; the marker simulates a disappearing tag.
   */
  await writeFile(
    wrapper,
    `#!/bin/sh
printf 'upload-pack\\n' >> '${fixture.tracePath}'
GIT_TRACE_PACKET='${fixture.tracePath}' git upload-pack "$@"
status=$?
if [ -f '${fixture.removeTagPath}' ]; then
  rm '${fixture.removeTagPath}'
  git --git-dir='${fixture.remotePath}' update-ref -d refs/tags/v1.0.0
fi
exit "$status"
`,
    { mode: 0o755 },
  )

  await configureRemote(fixture)
  await runGit(fixture, ['init', '--template=', fixture.workPath])
  await runGit(fixture, ['init', '--bare', '--template=', fixture.remotePath])

  await publishRelease(fixture, '1.0.0', {
    typescript: '# TypeScript Rules\n\nUse explicit boundary types.\n',
    vue: '# Vue Rules\n\nUse component contracts.\n',
    python: '# Python Rules\n\nUse Python type hints.\n',
  })

  await publishRelease(fixture, '1.9.0', {
    python: '# Python Rules\n\nOld stable release.\n',
  })

  await publishRelease(fixture, '1.10.0', {
    typescript: '# TypeScript Rules\n\nValidate external boundaries.\n',
    vue: '# Vue Rules\n\nPreserve component contracts.\n',
    python: '# Python Rules\n\nNew stable release.\n',
  })

  await setTags(fixture, ['v1.0.0'])

  for (const [name, content] of Object.entries(unrelatedFiles)) {
    await writeFile(join(directory, name), content)
  }

  await runGit(fixture, ['init', '--template=', directory])
  await runGit(fixture, ['add', 'notes.txt'], directory)
  await runGit(fixture, ['commit', '-m', 'Consumer sentinel'], directory)

  fixture.gitSnapshot = await snapshotGit(join(directory, '.git'))

  return fixture
}

/**
 * Read the fixture directory entries and return a sorted copy for file-set checks.
 */
async function getFileNames(fixture) {
  const names = await readdir(fixture.directory)

  return names.filter((name) => name !== '.git').toSorted()
}

/**
 * Read the generated fixture document, assert a YAML front matter boundary and
 * return its original bytes, header, body and parsed standards configuration.
 */
async function getCoding(fixture) {
  const content = await readFile(fixture.codingPath, 'utf8')
  const end = content.indexOf('\n---\n', 4)

  assert.ok(
    content.startsWith('---\n') && end > 0,
    'Expected YAML front matter',
  )

  return {
    content,
    header: content.slice(0, end + 5),
    body: content.slice(end + 5),
    config: parse(content.slice(4, end)).codingStandards,
  }
}

/**
 * Generate version 1.0.0 in the fixture directory using the supplied profile order,
 * assert successful CLI execution and return the generated document for checks.
 */
async function initialize(fixture, profiles = ['typescript', 'vue']) {
  const result = await runCli(
    [
      'init',
      '-C',
      fixture.directory,
      '--version',
      '1.0.0',
      '--profiles',
      ...profiles,
    ],
    fixture,
  )

  assert.equal(result.status, 0, result.stderr)

  return getCoding(fixture)
}

/**
 * Produce consumer-maintained YAML with the supplied profile order and pinned
 * release, including comments and private metadata used to detect unwanted changes
 * or disclosure during generation.
 */
function customHeader(fixture, profiles = ['typescript', 'vue']) {
  return `---
# Consumer-maintained metadata, not generated rules
source: https://github.com/company/consumer
metadata:
  privateNote: "${secret}"
codingStandards:
  repository: ${repository} # rules source
  version: "1.0.0" # keep this comment
  revision: '${fixture.versions['1.0.0'].sha}' # immutable commit
  profiles: [${profiles.join(', ')}] # explicit order
  owner: platform-team
ticket: ENG-123
---
`
}

